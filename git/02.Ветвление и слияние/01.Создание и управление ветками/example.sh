# Ветвление и слияние: Основные концепции

# Ветки (branches) — это одна из самых мощных и уникальных особенностей Git.
# Они позволяют разрабатывать новые функции, исправлять баги и экспериментировать
# изолированно от основной кодовой базы.

# ---- Проверка текущей ветки ----
git branch

# ---- Создание новой ветки ----
git branch feature/new-login

# ---- Переключение на ветку ----
git checkout feature/new-login

# ---- Создание и переключение одной командой ----
git checkout -b feature/new-login

# ---- Просмотр всех веток (включая удаленные) ----
git branch -a

# ---- Удаление ветки ----
git branch -d feature/new-login

# ---- Принудительное удаление (если изменения не слиты) ----
git branch -D feature/new-login