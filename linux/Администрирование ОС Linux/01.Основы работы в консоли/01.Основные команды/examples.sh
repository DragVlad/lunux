# Основные команды Linux - практические примеры

# Навигация
pwd                                      # показать текущую директорию
cd /tmp                                  # перейти в /tmp
cd ~                                     # перейти в домашнюю директорию
cd ..                                    # подняться на уровень выше

# Просмотр содержимого
ls                                       # список файлов
ls -l                                    # подробный список
ls -a                                    # со скрытыми файлами

# Работа с файлами
touch file.txt                           # создать файл
echo "text" > file.txt                   # записать текст в файл
echo "more" >> file.txt                  # добавить текст в конец
cat file.txt                             # показать содержимое
head -n 5 file.txt                       # показать первые 5 строк
tail -n 5 file.txt                       # показать последние 5 строк
tail -f file.txt                         # следить за файлом в реальном времени

# Копирование и перемещение
cp source.txt dest.txt                   # скопировать файл
cp -r source_dir dest_dir                # скопировать директорию
mv old.txt new.txt                       # переименовать/переместить

# Создание и удаление
mkdir newdir                             # создать директорию
mkdir -p path/to/dir                     # создать вложенные директории
rm file.txt                              # удалить файл
rm -r dir/                               # удалить директорию
rm -rf dir/                              # удалить директорию без подтверждения

# Поиск
grep "text" file.txt                     # искать текст в файле
grep -r "text" /path/                    # искать рекурсивно
find /path -name "*.txt"                 # найти файлы по имени

# Процессы
ps                                       # показать мои процессы
ps aux                                   # показать все процессы
kill PID                                 # завершить процесс по PID
kill -9 PID                              # принудительно завершить

# Сеть
ping google.com                          # проверить соединение
ip a                                     # показать сетевые интерфейсы
ss -tuln                                 # показать открытые порты

# Диски
df -h                                    # свободное место на дисках
du -sh /path                             # размер директории

# Справка
man ls                                   # полная документация
ls --help                                # краткая справка

# Очистка
rm -rf /tmp/linux_practice               # удалить тестовую директорию